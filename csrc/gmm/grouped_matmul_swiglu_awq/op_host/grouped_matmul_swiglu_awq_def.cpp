/*!
 * \file grouped_matmul_swiglu_awq_def.cpp
 * \brief Op definition for grouped_matmul_swiglu_awq.
 */

#include "register/op_def_registry.h"

namespace ops {
class GroupedMatmulSwigluAwq : public OpDef {
public:
    explicit GroupedMatmulSwigluAwq(const char *name) : OpDef(name)
    {
        this->Input("x")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16, ge::DT_BF16})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND});
        // AWQ gate-up projection: int32-packed signed int4 weights for all groups,
        // stacked along the leading expert dimension. Using REQUIRED tensors instead
        // of DYNAMIC lists keeps group_num out of the CANN binary key so one binary
        // works for any number of experts.
        this->Input("weight1")
            .ParamType(REQUIRED)
            .DataType({ge::DT_INT32, ge::DT_INT32})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND});
        this->Input("weight1_scale")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16, ge::DT_BF16})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND});
        this->Input("weight1_offset")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16, ge::DT_BF16})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND});
        // AWQ down projection: int32-packed signed int4 weights for all groups.
        this->Input("weight2")
            .ParamType(REQUIRED)
            .DataType({ge::DT_INT32, ge::DT_INT32})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND});
        this->Input("weight2_scale")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16, ge::DT_BF16})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND});
        this->Input("weight2_offset")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16, ge::DT_BF16})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND});
        this->Input("group_list")
            .ParamType(REQUIRED)
            .DataType({ge::DT_INT64, ge::DT_INT64})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND});

        this->Output("y")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16, ge::DT_BF16})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND});

        this->Attr("group_list_type")
            .AttrType(OPTIONAL)
            .Int(1);
        this->Attr("group_size")
            .AttrType(OPTIONAL)
            .Int(128);
        this->Attr("swiglu_limit")
            .AttrType(OPTIONAL)
            .Float(0.0f);

        OpAICoreConfig aicore_config;
        aicore_config.DynamicCompileStaticFlag(true)
            .DynamicFormatFlag(true)
            .DynamicRankSupportFlag(true)
            .DynamicShapeSupportFlag(true)
            .NeedCheckSupportFlag(false)
            .PrecisionReduceFlag(true);
        this->AICore().AddConfig("ascend910b", aicore_config);
        this->AICore().AddConfig("ascend910_93", aicore_config);
    }
};

OP_ADD(GroupedMatmulSwigluAwq);
} // namespace ops
